/**
 * Writes app/palettes.css from lib/palettes.ts and refuses to write it when a
 * palette fails contrast.
 *
 * Each palette names eight roles; every other token the stage reads (hairlines,
 * the sunk and high surface steps, the RGB triplets the WebGL field reads) is
 * derived here, so a palette cannot drift from the structure of the shipped one.
 * The derived values are written as literals because check-ramps.ts and the
 * renderer both read resolved colours, not color-mix() expressions.
 *
 * Floors (WCAG 2.x, sRGB): ink on ground 7:1, soft ink and accent on ground
 * 4.5:1, text on the accent 4.5:1, ink on the sheet 7:1, accent on the raised
 * surface 3:1 (it marks controls there, it does not carry body text).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { formatRgb, oklch, parse, wcagContrast, type Oklch } from "culori";
import { DEFAULT_PALETTE, palettes, type PaletteRoles } from "../lib/palettes";

const lch = (s: string): Oklch => {
  const c = oklch(parse(s));
  if (!c) throw new Error(`unparseable colour ${s}`);
  return c;
};

const fmt = ({ l, c, h }: Oklch, alpha?: number) =>
  `oklch(${+l.toFixed(4)} ${+(c ?? 0).toFixed(4)} ${+(h ?? 0).toFixed(2)}${alpha === undefined ? "" : ` / ${alpha}`})`;

const shift = (s: string, dl: number) => {
  const c = lch(s);
  return fmt({ ...c, l: Math.min(Math.max(c.l + dl, 0), 1) });
};

const alpha = (s: string, a: number) => fmt(lch(s), a);

/** Mix in OKLCH by lightness only, keeping the first colour's hue and chroma. */
const towards = (a: string, b: string, t: number) => {
  const x = lch(a);
  return fmt({ ...x, l: x.l + (lch(b).l - x.l) * t });
};

const rgbTriplet = (s: string) => {
  const m = formatRgb(parse(s)!).match(/\d+/g)!;
  return m.slice(0, 3).join(" ");
};

const FLOORS: [keyof PaletteRoles, keyof PaletteRoles, number][] = [
  ["ink", "ground", 7],
  ["inkSoft", "ground", 4.5],
  ["accent", "ground", 4.5],
  ["onAccent", "accent", 4.5],
  ["inkOnSheet", "sheet", 7],
  ["accent", "raised", 3],
];

let failures = 0;
const report: string[] = [];
for (const p of palettes) {
  const cells = FLOORS.map(([fg, bg, floor]) => {
    const ratio = wcagContrast(p.roles[fg], p.roles[bg]);
    if (ratio < floor) {
      failures++;
      console.error(`  ${p.id}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, floor ${floor}:1`);
    }
    return ratio.toFixed(1);
  });
  report.push(`  ${p.id.padEnd(11)} ${cells.join("  ")}`);
}
console.log(`  palette     ${FLOORS.map(([f, b]) => `${f}/${b}`).join("  ")}`);
console.log(report.join("\n"));
if (failures) {
  console.error(`\n${failures} pair(s) below their floor; app/palettes.css not written.`);
  process.exit(1);
}

function block(p: (typeof palettes)[number]) {
  const r = p.roles;
  const at = `html[data-palette="${p.id}"]`;
  const inkFaint = towards(r.ink, r.ground, 0.4);
  return `/* ${p.label}. ${p.source}. */
${at} [data-stage] {
  --void: ${r.ground};
  --void-raised: ${r.raised};
  --sheet: ${r.sheet};
  --ink-on-void: ${r.ink};
  --ink-on-void-soft: ${r.inkSoft};
  --ink-on-sheet: ${r.inkOnSheet};
  --ink-on-sheet-soft: ${towards(r.inkOnSheet, r.sheet, 0.32)};
  --voltage: ${r.accent};
  --voltage-rgb: ${rgbTriplet(r.accent)};
  --ink-rgb: ${rgbTriplet(r.ink)};
  --hair: ${alpha(r.ink, 0.14)};
  --hair-strong: ${alpha(r.ink, 0.26)};
  --paper-sunk: ${shift(r.ground, -0.03)};
  --paper-high: ${shift(r.raised, 0.045)};
  --ink-faint: ${inkFaint};
  --rule: ${shift(r.ground, 0.16)};
  --signal-deep: ${shift(r.accent, 0.035)};
  --on-signal: ${r.onAccent};
  --surface-1: ${towards(r.ground, r.raised, 0.5)};
  caret-color: ${r.accent};
}
${at} [data-stage] [data-surface="console"] {
  --paper-sunk: ${shift(r.raised, -0.035)};
  --paper-raised: ${shift(r.raised, 0.035)};
  --paper-high: ${shift(r.raised, 0.075)};
  --ink-faint: ${inkFaint};
  --rule: ${shift(r.raised, 0.135)};
  --on-signal: ${r.onAccent};
}
${at} [data-stage] [data-surface="sheet"] {
  --hair: ${alpha(r.inkOnSheet, 0.14)};
  --hair-strong: ${alpha(r.inkOnSheet, 0.26)};
}
${at} [data-stage] [data-ground="voltage"] {
  --ink: ${r.onAccent};
  --ink-soft: ${alpha(r.onAccent, 0.72)};
}
${at} [data-stage] ::selection {
  background: ${r.accent};
  color: ${r.onAccent};
}
${at}:has([data-stage]) {
  background: ${r.ground};
  scrollbar-color: ${shift(r.ground, 0.26)} ${r.ground};
}
`;
}

const css = `/*
 * Generated by scripts/build-palettes.ts from lib/palettes.ts. Do not edit.
 *
 * Alternate stage palettes, applied by data-palette on <html>. "${DEFAULT_PALETTE}" is
 * app/stage.css itself and is not restated: without the attribute nothing here
 * matches.
 */
${palettes
  .filter((p) => p.id !== DEFAULT_PALETTE)
  .map(block)
  .join("\n")}`;

writeFileSync(join(process.cwd(), "app/palettes.css"), css);
console.log(`\nWrote app/palettes.css (${palettes.length - 1} palettes).`);
