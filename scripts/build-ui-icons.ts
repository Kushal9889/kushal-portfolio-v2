const root = join(process.cwd(), "node_modules/@phosphor-icons/core/assets");
const kebab = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();
const entries: string[] = [];
const missing: string[] = [];

for (const [name, weights] of Object.entries(INVENTORY)) {
  for (const weight of weights) {
    const file = join(root, weight, weight === "regular" ? `${kebab(name)}.svg` : `${kebab(name)}-${weight}.svg`);
    if (!existsSync(file)) {
      missing.push(`${name} ${weight}`);
      continue;
    }
    const body = readFileSync(file, "utf8").replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
    entries.push(`  ${JSON.stringify(`${name}:${weight}`)}: ${JSON.stringify(body)},`);
  }
}

if (missing.length) {
  console.error("Phosphor core has no glyph for:", missing.join(", "));
  process.exit(1);
}

writeFileSync(
  join(process.cwd(), "lib/ui-icons.ts"),
  `// Generated by scripts/build-ui-icons.ts from @phosphor-icons/core (MIT). Do not edit.
// Inner SVG markup on Phosphor's 256 by 256 grid, keyed "Name:weight".

export const UI_ICONS = {
${entries.join("\n")}
} as const;

export type GlyphKey = keyof typeof UI_ICONS;
`,
);
console.log(`ui-icons: ${entries.length} glyphs`);
